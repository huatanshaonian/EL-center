def slots(code):
    """返回走线孔（板自身坐标）：[(中心 x, 中心 y, 宽, 长)]"""
    if code not in SLOTS:
        return []
    ox, oy = GRID[code][0]
    return [(x - ox, y - oy, w, h) for x, y, w, h in SLOTS[code]]


def grid_holes(code):
    """返回该板孔阵孔心（板自身坐标）；没有孔阵返回 []"""
    if code not in GRID:
        return []
    (ox, oy), (x0, x1, y0, y1) = GRID[code]
    return [(x - ox, y - oy) for x in range(x0, x1 + 1, 10) for y in range(y0, y1 + 1, 10)]

