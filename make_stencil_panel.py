"""把几块板的顶层锡膏层（GTP）拼到一张钢网上：各板平移后合并成一个 GTP，板框合并成一个 GKO（只作对位参考）。
嘉立创钢网最小 30×40 cm，三块板（01 EL-IF、02 PWR-DIST、06 IV18）各订一张太浪费，拼一张单独下钢网单。
要求各板 Gerber 同为毫米、%FSLAX45Y45%（嘉立创EDA 导出满足，脚本会检查）。
用法：python make_stencil_panel.py      输出 el_driver/下单文件_20261022/00_钢网_三板合一/
"""
import os
import re
import zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
ED = os.path.join(ROOT, 'el_driver')
OUT_DIR = os.path.join(ED, '下单文件_20261022', '00_钢网_三板合一')
GAP = 15.0  # 板与板之间留的距离 mm

# 标签, Gerber 压缩包, 板宽, 板高（mm，板框左下角都在 0,0）——从下往上竖着排
BOARDS = [
    ('PWR-DIST', 'PWR-DIST_D1/制板文件/Gerber_PWR-DIST_D1.1.zip', 150, 100),
    ('EL-IF', 'D1.3/制板文件/Gerber_EL-IF_D1.3.zip', 100, 100),
    ('IV18', 'IV18_D1/制板文件/Gerber_IV18_D1.zip', 130, 37),
]
HEADER = '%FSLAX45Y45*%'
SCALE = 10 ** 5


def split(txt):
    """拆成 (宏定义, 光圈定义, 图形语句)；检查格式"""
    assert HEADER in txt and '%MOMM*%' in txt, '格式不是 mm / 4.5'
    # 圆弧的 I/J 是相对起点的偏移，平移时不用改，只改 X/Y
    macros = re.findall(r'%AM[^%]*%', txt)
    aps = re.findall(r'%ADD\d+[^%]*%', txt)
    body = re.sub(r'%[^%]*%', '', txt)
    body = [ln for ln in body.splitlines() if ln.strip() and not ln.startswith('G04') and ln.strip() not in ('M02*', 'G75*')]
    return macros, aps, body


def shift_body(body, dx, dy, dmap, tag):
    out = []
    for ln in body:
        ln = re.sub(r'D(\d+)\*', lambda m: f'D{dmap.get(int(m.group(1)), int(m.group(1)))}*', ln) if re.match(r'^(G54)?D\d+\*$', ln) else ln
        ln = re.sub(r'X(-?\d+)', lambda m: f'X{int(m.group(1)) + round(dx * SCALE)}', ln)
        ln = re.sub(r'Y(-?\d+)', lambda m: f'Y{int(m.group(1)) + round(dy * SCALE)}', ln)
        out.append(ln)
    return out


def merge(layer):
    macros, aps, body = [], [], []
    next_d, y = 10, 0.0
    for tag, zp, w, h in BOARDS:
        txt = zipfile.ZipFile(os.path.join(ED, zp)).read(layer).decode('utf-8')
        m, a, b = split(txt)
        pre = tag.replace('-', '_')  # Gerber 名字里不能有减号
        for s in m:  # 宏名加板名前缀避免重名
            name = re.match(r'%AM([^*]+)\*', s).group(1)
            macros.append(s.replace(f'%AM{name}*', f'%AM{pre}_{name}*'))
            a = [x.replace(f',{name}*', f',{pre}_{name}*').replace(f'{name}*%', f'{pre}_{name}*%') for x in a]
        dmap = {}
        for s in a:
            d = int(re.match(r'%ADD(\d+)', s).group(1))
            dmap[d] = next_d
            aps.append(re.sub(r'^%ADD\d+', f'%ADD{next_d}', s))
            next_d += 1
        body.append(f'G04 Board {tag} offset Y {y:.1f} mm*')
        body += shift_body(b, 0.0, y, dmap, tag)
        y += h + GAP
    head = [f'G04 Layer: {layer} panel {"+".join(t for t, *_ in BOARDS)}*', 'G04 Generated by make_stencil_panel.py*',
            HEADER, '%MOMM*%']
    return '\n'.join(head + macros + aps + ['G75*'] + body + ['M02*']) + '\n', y - GAP


if __name__ == '__main__':
    os.makedirs(OUT_DIR, exist_ok=True)
    gtp, height = merge('Gerber_TopPasteMaskLayer.GTP')
    gko, _ = merge('Gerber_BoardOutlineLayer.GKO')
    zp = os.path.join(OUT_DIR, '钢网_EL-IF+PWR-DIST+IV18.zip')
    with zipfile.ZipFile(zp, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('Gerber_TopPasteMaskLayer.GTP', gtp)
        z.writestr('Gerber_BoardOutlineLayer.GKO', gko)
    print(f'拼板外形 {max(w for _, _, w, _ in BOARDS)} × {height:.0f} mm -> {zp}')
